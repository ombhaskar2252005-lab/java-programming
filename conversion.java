public class conversion {
    public static void main(){
        int myInt = 9;
        double myDouble = myInt; //implicit conversion
        System.out.println(myDouble);

        //explicit conversion
        double math = 12.3;
        int math1 = (int)math;
        System.out.println(math1);
        System.out.println("My Name Is Bhaskar Ranjan");
    }
    
}
